function hydrateIcons(root = document) {
  root.querySelectorAll('.ico[data-i]').forEach((el) => {
    if (!el.dataset.done) {
      el.innerHTML = icon(el.dataset.i);
      el.dataset.done = '1';
    }
  });
}
